def author_skills(Art,assets,ROOT):
 import json
 inventory=json.loads((ROOT/'assets-src/portfolio/skill-inventory.json').read_text())
 assert {item['id'] for item in inventory}==set(SYMBOLS),'Re-export inventory and author missing symbols.'
 for entry in inventory:
  rows=SYMBOLS[entry['id']];category=entry['category']
  accent='#3C5CA8' if category in ['LANGUAGE','DATABASE','FRONTEND'] else '#1D7F6E'
  for size in [16,32]:
   a=Art(size,size);factor=1 if size==16 else 3;ox=(size-7*factor)//2;oy=ox
   # A one-pixel rim with an opaque light inset makes the diagram legible at native resolution.
   for y,row in enumerate(rows):
    for x,bit in enumerate(row):
     if bit=='1':a.rect(ox+x*factor,oy+y*factor,factor,factor,'#183B34')
   for y,row in enumerate(rows):
    for x,bit in enumerate(row):
     if bit=='1':
      if size==16:a.dot(ox+x,oy+y,accent if y%3 else '#183B34')
      else:a.rect(ox+x*factor+1,oy+y*factor+1,1,1,accent)
   # Authored corner legend denotes the content category, with no numeric rank.
   if size==32:
    a.rect(3,27,4,1,accent);a.rect(3,28,2,1,'#6FD3B5')
   assets['skill-'+entry['id']+('-large' if size==32 else '')]=a
